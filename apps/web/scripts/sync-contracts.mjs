// Copies contract ABIs (from `forge build`) and deployed addresses (from the deploy scripts)
// into typed TypeScript under shared/, which the web app AND the API import.
//
// The output is COMMITTED: Vercel builds the web app without Foundry, so it can't regenerate it.
// CI re-runs this and fails if the committed copy is stale.
//
//   npm run sync           # after `forge build` / a deploy
//   npm run sync -- --if-available   # (predev) skip quietly when contracts/out doesn't exist
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
const contractsDir = join(web, '..', '..', 'contracts');
const outDir = join(contractsDir, 'out');
const deploymentsDir = join(contractsDir, 'deployments');
const sharedDir = join(web, 'shared');
const optional = process.argv.includes('--if-available');

// One ABI can serve several deployments (three merchants share `Merchant`).
const CONTRACTS = ['DavaoCoin', 'DavaoBank', 'PuzzleRewards', 'DurianMarket', 'DavaoItems', 'DurianMine', 'Merchant'];

if (!existsSync(outDir)) {
  if (optional) process.exit(0);
  console.error('contracts/out not found. Run `forge build` in contracts/ first.');
  process.exit(1);
}

const lowerFirst = (s) => s[0].toLowerCase() + s.slice(1);
const HEADER = '// GENERATED by scripts/sync-contracts.mjs from the Foundry build. Do not edit; run `npm run sync`.\n';

/* ---------------------------------------------------------------- ABIs */

let abis = HEADER;
for (const name of CONTRACTS) {
  const artifact = join(outDir, `${name}.sol`, `${name}.json`);
  if (!existsSync(artifact)) {
    console.error(`${artifact} not found. Run \`forge build\` in contracts/.`);
    process.exit(1);
  }
  const { abi } = JSON.parse(readFileSync(artifact, 'utf8'));
  abis += `\nexport const ${lowerFirst(name)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
}

/* --------------------------------------------------------- deployments */

const deployments = {};
if (existsSync(deploymentsDir)) {
  for (const file of readdirSync(deploymentsDir).filter((f) => /^\d+\.json$/.test(f))) {
    const d = JSON.parse(readFileSync(join(deploymentsDir, file), 'utf8'));
    const { chainId, startBlock, ...addresses } = d;
    deployments[chainId] = { startBlock, addresses: Object.fromEntries(Object.entries(addresses).sort()) };
  }
}

let deps = HEADER;
deps += '// Contract addresses per chain id, written by contracts/script/Deploy*.s.sol.\n\n';
deps += `export const DEPLOYMENTS = ${JSON.stringify(deployments, null, 2)} as const;\n`;

mkdirSync(sharedDir, { recursive: true });
writeFileSync(join(sharedDir, 'abis.ts'), abis);
writeFileSync(join(sharedDir, 'deployments.ts'), deps);
console.log(`Synced ${CONTRACTS.length} ABIs and ${Object.keys(deployments).length} deployment(s) -> shared/`);
